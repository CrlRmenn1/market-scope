const VERDICT_TONE = {
  high: [COLOR.good, COLOR.goodSoft],
  medium: [COLOR.mid, COLOR.midSoft],
  low: [COLOR.bad, COLOR.badSoft],
  blocked: [COLOR.bad, COLOR.badSoft],
  unknown: [COLOR.muted, COLOR.unknownSoft]
};

const PAGE_SIZES_MM = { a4: [210, 297], letter: [215.9, 279.4] };
const DEFAULT_MARGIN_MM = 18;

// Size of the site map on the page, in mm. The map image is rendered to this shape
// (utils/siteMapImage.js) before the PDF is built.
export const getSiteMapBox = (options = {}) => {
  const [shortSide, longSide] = PAGE_SIZES_MM[options.format] || PAGE_SIZES_MM.a4;
  const landscape = options.orientation === 'landscape';
  const pageW = landscape ? longSide : shortSide;
  const pageH = landscape ? shortSide : longSide;
  const margin = Number(options.marginMm) || DEFAULT_MARGIN_MM;
  const width = pageW - 2 * margin;
  // Short enough to share the first page with the title and score summary (about 120 mm).
  const height = Math.min(width * 0.56, 95, Math.max(55, pageH - 2 * margin - 120));
  return { width, height };
};

// A see-through map colour as the solid colour it shows on white paper.
const onWhite = (hex, alpha) => {
  const value = parseInt(hex.slice(1), 16);
  const mix = (channel) => Math.round(255 - (255 - channel) * alpha);
  const r = mix((value >> 16) & 255);
  const g = mix((value >> 8) & 255);
  const b = mix(value & 255);
  return `#${[r, g, b].map((c) => c.toString(16).padStart(2, '0')).join('')}`;
};

const FACTOR_ORDER = ['zoning', 'hazard', 'competition_density', 'road_access', 'anchor_proximity', 'building_density', 'saturation'];

// The section headings the AI is asked to write (services/reporting.py REPORT_SECTIONS).
const NARRATIVE_SECTIONS = [
  'Executive Summary',
  'Location Snapshot',
  'Zoning Status',
  'Hazard Status',
  'Saturation Assessment',
  'Demand and Anchor Commentary',
  'Recommendation',
  'Next Actions'
];

const DISCLAIMER = 'This report is generated by automated MCDA geospatial models from map, zoning, hazard and proxy data. '
  + 'It is a guide, not a guarantee. Please secure BPLO clearances from Panabo City Hall before investment.';

// The built-in PDF font only has Latin-1 characters; anything else would print as junk.
const REPLACEMENTS = [
  [/[\u2018\u2019\u201A\u2032]/g, "'"],
  [/[\u201C\u201D\u201E\u2033]/g, '"'],
  [/[\u2013\u2212]/g, '-'],
  [/\s*\u2014\s*/g, ' - '],
  [/\u2026/g, '...'],
  [/\u20B1/g, 'PHP '],
  [/\u2265/g, '>='],
  [/\u2264/g, '<='],
  [/[\u2192\u2794\u27A1]/g, '->'],
  [/[\u2022\u25CF\u25AA\u25E6]/g, '-'],
  [/[\u00A0\u2009\u202F]/g, ' ']
];

const clean = (value) => {
  let text = String(value ?? '');
  REPLACEMENTS.forEach(([pattern, replacement]) => { text = text.replace(pattern, replacement); });
  return text.replace(/[^\t\n\r\x20-\x7E\u00A1-\u00FF]/g, '');
};

// Gemini sometimes adds Markdown even when told not to.
const stripInline = (text) => text
  .replace(/\*\*(.+?)\*\*/g, '$1')
  .replace(/__(.+?)__/g, '$1')
  .replace(/`([^`]*)`/g, '$1')
  .replace(/(^|[\s(])\*([^*\s][^*]*?)\*(?=[\s).,;:!?]|$)/g, '$1$2');

const matchSection = (text) => {
  const lower = text.toLowerCase();
  for (const name of NARRATIVE_SECTIONS) {
    const key = name.toLowerCase();
    if (lower === key || lower === `${key}:`) return { name, rest: '' };
    if (lower.startsWith(`${key}:`)) return { name, rest: text.slice(name.length + 1).trim() };
  }
  return null;
};

// Turns the narrative text into headings, paragraphs and list items.
export const parseNarrative = (narrative) => {
  const blocks = [];
  let paragraph = [];
  const flush = () => {
    if (paragraph.length) blocks.push({ type: 'paragraph', text: paragraph.join(' ') });
    paragraph = [];
  };

  String(narrative || '').split(/\r?\n/).forEach((raw) => {
    let text = raw.trim();
    if (!text) {
      flush();
      return;
    }

    const markdownHeading = /^#{1,6}\s+/.test(text);
    text = text.replace(/^#{1,6}\s+/, '');

    let type = 'paragraph';
    let marker = '';
    let match = text.match(/^[-*\u2022]\s+(.*)$/);
    if (match) {
      type = 'bullet';
      text = match[1];
    } else if ((match = text.match(/^(\d+)[.)]\s+(.*)$/))) {
      type = 'numbered';
      marker = `${match[1]}.`;
      text = match[2];
    }
    text = stripInline(text).trim();

    const section = type === 'bullet' ? null : matchSection(text);
    if (section || markdownHeading) {
      flush();
      blocks.push({ type: 'heading', text: section ? section.name : text.replace(/:$/, '') });
      if (section?.rest) paragraph.push(section.rest);
      return;
    }
    if (type === 'paragraph') {
      paragraph.push(text);
      return;
    }
    flush();
    blocks.push({ type, marker, text });
  });
  flush();
  return blocks;
};

const factorColor = (factor) => {
  if (factor?.constraint) {
    if (factor.state === 'permitted') return COLOR.good;
    if (factor.state === 'not_permitted') return COLOR.bad;
    return COLOR.faint;
  }
  const score = factor?.score;
  if (score === null || score === undefined) return COLOR.faint;
  if (score >= 20) return COLOR.good;
  if (score >= 10) return COLOR.mid;
  return COLOR.bad;
};

const formatCoords = (coords) => {
  const lat = Number(coords?.lat ?? coords?.latitude);
  const lng = Number(coords?.lng ?? coords?.lon ?? coords?.longitude);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return 'Not recorded';
  return `${lat.toFixed(5)}, ${lng.toFixed(5)}`;
};

const formatPrice = (min, max) => {
  const low = Number(min || 0);
  const high = Number(max || 0);
  if (low > 0 && high > 0) return `PHP ${low.toLocaleString('en-US')} - PHP ${high.toLocaleString('en-US')}`;
  if (low > 0) return `From PHP ${low.toLocaleString('en-US')}`;
  if (high > 0) return `Up to PHP ${high.toLocaleString('en-US')}`;
  return 'Not set';
};

const narrativeSource = (meta, qc) => {
  if (!meta) return '';
  if (meta.used_llm) {
    const model = meta.model ? ` (${meta.model})` : '';
    const check = qc?.valid ? 'Its key figures were checked against the scan.' : 'Some figures could not be matched to the scan, so compare it with the factor table.';
    return `Written by generative AI${model} using only this scan's data. ${check}`;
  }
  return 'Written from a fixed template because the AI service was unavailable.';
};

/**
 * Builds the report PDF and returns the jsPDF document (call .save(filename) on it).
 * data: the scan result shown on the report page. narrative / narrativeMeta / narrativeQc: the
 * AI narrative and its generation details. siteMap: the map image from renderSiteMapImage plus
 * { competitorColor, competitorCount, anchorCount }, or null to leave the map out.
 * options: { format, orientation, marginMm, generatedAt }.
 */
export const buildReportPdf = ({ data, targetCoords, narrative, narrativeMeta, narrativeQc, siteMap, options = {} }) => {
  const doc = new jsPDF({
    unit: 'mm',
    format: options.format || 'a4',
    orientation: options.orientation || 'portrait',
    compress: true
  });

  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = Number(options.marginMm) || DEFAULT_MARGIN_MM;
  const left = margin;
  const right = pageW - margin;
  const contentW = right - left;
  const footerY = pageH - margin + 3;
  const contentBottom = footerY - 6;

  const breakdown = data?.breakdown || {};
  const verdict = getVerdict(data);
  const notPermitted = verdict.key === 'not_permitted';
  const [toneColor, toneSoft] = VERDICT_TONE[verdict.tone] || VERDICT_TONE.unknown;
  const businessLabel = data?.business_label || getBusinessTypeLabel(data?.business_type) || data?.business_type || 'Business';
  const space = data?.space_context || data?.selected_space || null;
  const generatedAt = options.generatedAt || new Date();
  const generatedText = generatedAt.toLocaleString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric', hour: 'numeric', minute: '2-digit'
  });

  doc.setProperties({
    title: `Business Feasibility Report - ${clean(businessLabel)}`,
    subject: 'MarketScope business site feasibility report',
    author: 'MarketScope',
    creator: 'MarketScope'
  });
  doc.setLineWidth(0.25);

  let y = margin;

  // ---- drawing helpers ----
  const lineHeight = (size, factor = 1.45) => size * 0.3528 * factor;
  const font = (size, color = COLOR.body, style = 'normal') => {
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    doc.setTextColor(color);
  };
  const put = (text, x, top, opts = {}) => doc.text(clean(text), x, top, { baseline: 'top', ...opts });
  const ensure = (height) => {
    if (y + height > contentBottom) {
      doc.addPage();
      y = margin;
    }
  };
  const measure = (text, { size = 10, style = 'normal', width = contentW, lh = 1.45 } = {}) => {
    font(size, COLOR.body, style);
    return doc.splitTextToSize(clean(text), width).length * lineHeight(size, lh);
  };
  const write = (text, { size = 10, color = COLOR.body, style = 'normal', x = left, width = contentW, lh = 1.45, after = 0 } = {}) => {
    font(size, color, style);
    const step = lineHeight(size, lh);
    doc.splitTextToSize(clean(text), width).forEach((line) => {
      ensure(step);
      font(size, color, style);
      put(line, x, y);
      y += step;
    });
    y += after;
  };
  const rule = (top = y, color = COLOR.rule) => {
    doc.setDrawColor(color);
    doc.line(left, top, right, top);
  };
  const fitText = (text, width) => {
    const lines = doc.splitTextToSize(clean(text), width);
    return lines.length > 1 ? `${lines[0].replace(/\s+\S*$/, '')}...` : (lines[0] || '');
  };
  const sectionHeading = (title, keepWith = 20) => {
    y += 5;
    ensure(10 + keepWith);
    doc.setFillColor(COLOR.accent);
    doc.rect(left, y + 0.4, 1.3, 5.2, 'F');
    font(13, COLOR.ink, 'bold');
    put(title, left + 4.5, y);
    y += lineHeight(13, 1.2) + 3;
  };
  const callout = (title, text, color, fill, border = color) => {
    const pad = 4.5;
    const textW = contentW - pad * 2;
    const height = pad * 2 + lineHeight(10, 1.4) + 1 + measure(text, { size: 9.5, width: textW, lh: 1.45 });
    ensure(height);
    doc.setFillColor(fill);
    doc.setDrawColor(border);
    doc.roundedRect(left, y, contentW, height, 2.5, 2.5, 'FD');
    const top = y;
    y += pad;
    font(10, color, 'bold');
    put(title, left + pad, y);
    y += lineHeight(10, 1.4) + 1;
    write(text, { size: 9.5, color: COLOR.body, x: left + pad, width: textW });
    y = top + height;
  };

  // ---- title block ----
  doc.setFillColor(COLOR.accent);
  doc.rect(0, 0, pageW, 2.5, 'F');
  font(8, COLOR.accent, 'bold');
  doc.setCharSpace(0.7);
  put('MARKETSCOPE', left, y);
  doc.setCharSpace(0);
  font(8, COLOR.faint);
  put('Panabo City business site analysis', right, y, { align: 'right' });
  y += 7;
  font(22, COLOR.ink, 'bold');
  put('Business Feasibility Report', left, y);
  y += lineHeight(22, 1.25);
  font(10.5, COLOR.muted);
  put(`${businessLabel}   |   Generated ${generatedText}`, left, y);
  y += lineHeight(10.5, 1.5) + 2;
  rule();
  y += 6;

  // ---- summary panel: score and key facts ----
  const zoning = breakdown.zoning;
  const hazard = breakdown.hazard;
  const facts = [
    ['Business type', businessLabel],
    ['Location (lat, lng)', formatCoords(targetCoords || data?.target_coords)],
    ['Scan radius', data?.radius_meters ? `${data.radius_meters} m` : 'Not recorded'],
    ['Competitors found', String(Math.max(0, Number(data?.competitors_found || 0)))],
    ['Zoning', zoning?.status || 'Not checked', factorColor(zoning)],
    ['Flood hazard', hazard?.status || 'Not checked', factorColor(hazard)]
  ];
  if (notPermitted && data?.market_potential_score !== undefined && data?.market_potential_score !== null) {
    facts.push(['Score if zoning allowed it', `${Math.round(Number(data.market_potential_score))}/100`]);
  }
  if (space?.title) facts.push(['Pinned space', space.title]);

  const rowStep = 5.6;
  const panelH = Math.max(46, 12 + facts.length * rowStep);
  const scoreColW = Math.min(60, contentW * 0.34);
  doc.setFillColor(COLOR.panel);
  doc.setDrawColor(COLOR.rule);
  doc.roundedRect(left, y, contentW, panelH, 3, 3, 'FD');

  const sx = left + 7;
  let sy = y + 7;
  font(7.5, COLOR.faint, 'bold');
  doc.setCharSpace(0.5);
  put('SUITABILITY SCORE', sx, sy);
  doc.setCharSpace(0);
  sy += 5;
  const scoreText = String(Math.round(Number(data?.viability_score || 0)));
  font(36, toneColor, 'bold');
  put(scoreText, sx, sy);
  const scoreWidth = doc.getTextWidth(scoreText);
  font(12, COLOR.faint);
  put('/100', sx + scoreWidth + 1.5, sy + lineHeight(36, 1) - lineHeight(12, 1.25));
  sy += lineHeight(36, 1.05) + 2.5;
  font(9, toneColor, 'bold');
  const pillW = doc.getTextWidth(clean(verdict.label)) + 8;
  doc.setFillColor(toneSoft);
  doc.roundedRect(sx, sy, pillW, 7, 3.5, 3.5, 'F');
  put(verdict.label, sx + 4, sy + 3.5, { baseline: 'middle' });

  doc.setDrawColor(COLOR.rule);
  doc.line(left + scoreColW, y + 6, left + scoreColW, y + panelH - 6);

  const fx = left + scoreColW + 7;
  const fRight = Math.min(right - 7, fx + 115);
  const labelW = Math.min(40, (fRight - fx) * 0.45);
  let fy = y + 7;
  facts.forEach(([label, value, color]) => {
    font(8.5, COLOR.faint);
    put(label, fx, fy);
    font(9.5, color || COLOR.ink, 'bold');
    put(fitText(value, fRight - fx - labelW - 2), fRight, fy, { align: 'right' });
    fy += rowStep;
  });
  y += panelH + 5;

  if (notPermitted) {
    callout('Not permitted at this location', `${verdict.reason || ''} This site is not an option unless the zoning changes.`.trim(), COLOR.bad, COLOR.badSoft);
    y += 2;
  } else if (verdict.reason) {
    write(verdict.reason, { size: 9.5, color: COLOR.muted, style: 'italic', after: 1 });
  }

  // ---- site map ----
  if (siteMap?.dataUrl) {
    const box = getSiteMapBox(options);
    sectionHeading('Site Map', box.height + 14);
    doc.addImage(siteMap.dataUrl, 'JPEG', left, y, box.width, box.height);
    doc.setDrawColor(COLOR.rule);
    doc.rect(left, y, box.width, box.height, 'S');
    y += box.height + 3.5;

    const legend = [
      { kind: 'site', label: 'Proposed site' },
      { kind: 'radius', label: `${Number(data?.radius_meters || 340)} m scan radius` },
      { kind: 'competitor', label: `Competitors (${siteMap.competitorCount ?? 0})` }
    ];
    if (siteMap.anchorCount > 0) legend.push({ kind: 'anchor', label: `Anchors counted (${siteMap.anchorCount})` });
    (siteMap.hazardLegend || []).forEach((item) => legend.push({
      kind: 'hazard',
      label: item.label,
      fill: onWhite(item.fillColor, Math.max(0.3, item.fillOpacity * 1.6)),
      stroke: item.color
    }));

    font(8, COLOR.muted);
    let lx = left;
    const rowH = 5;
    ensure(rowH);
    legend.forEach((item) => {
      const itemW = 4.5 + doc.getTextWidth(clean(item.label)) + 5;
      if (lx + itemW > right) {
        lx = left;
        y += rowH;
        ensure(rowH);
      }
      const cy = y + 1.4;
      if (item.kind === 'site') {
        doc.setFillColor('#ddd2fb');
        doc.circle(lx + 1.6, cy, 1.6, 'F');
        doc.setFillColor('#7c3aed');
        doc.circle(lx + 1.6, cy, 0.8, 'F');
      } else if (item.kind === 'radius') {
        doc.setDrawColor('#7c3aed');
        doc.setLineWidth(0.45);
        doc.circle(lx + 1.6, cy, 1.4, 'S');
        doc.setLineWidth(0.25);
      } else if (item.kind === 'competitor') {
        doc.setFillColor(siteMap.competitorColor || '#ef4444');
        doc.circle(lx + 1.6, cy, 1.2, 'F');
      } else if (item.kind === 'anchor') {
        doc.setFillColor('#171717');
        doc.lines([[1.3, 1.3], [-1.3, 1.3], [-1.3, -1.3]], lx + 1.6, cy - 1.3, [1, 1], 'F', true);
      } else {
        doc.setFillColor(item.fill);
        doc.setDrawColor(item.stroke);
        doc.rect(lx, cy - 1.2, 3.2, 2.4, 'FD');
      }
      font(8, COLOR.muted);
      put(item.label, lx + 4.5, y);
      lx += itemW;
    });
    y += rowH;
  }

  // ---- strategic recommendation ----
  sectionHeading('Strategic Recommendation');
  write(data?.insight || 'No recommendation was recorded for this scan.', { size: 10.5, color: COLOR.ink, after: 1.5 });
  (data?.data_quality?.notes || []).forEach((note) => {
    write(`Note: ${note}`, { size: 8.5, color: COLOR.faint, after: 0.5 });
  });

  // ---- AI narrative ----
  sectionHeading('AI Feasibility Narrative', 25);
  const source = narrativeSource(narrativeMeta, narrativeQc);
  if (source) write(source, { size: 8.5, color: COLOR.faint, style: 'italic', after: 2 });

  const blocks = parseNarrative(narrative);
  if (blocks.length === 0) {
    callout(
      'Narrative not available',
      'The AI narrative could not be written when this PDF was made, so this copy has none. Open the report, click Generate AI, then save the PDF again.',
      COLOR.muted,
      COLOR.unknownSoft,
      COLOR.rule
    );
  }
  blocks.forEach((block, index) => {
    if (block.type === 'heading') {
      y += index === 0 ? 0 : 3;
      ensure(lineHeight(11, 1.3) + 12);
      font(11, COLOR.accent, 'bold');
      put(block.text, left, y);
      y += lineHeight(11, 1.3) + 0.8;
      return;
    }
    if (block.type === 'paragraph') {
      write(block.text, { size: 10, after: 2 });
      return;
    }
    const indent = 6;
    ensure(lineHeight(10));
    if (block.type === 'bullet') {
      doc.setFillColor(COLOR.accent);
      doc.circle(left + 2, y + lineHeight(10, 1) * 0.55, 0.65, 'F');
    } else {
      font(10, COLOR.accent, 'bold');
      put(block.marker, left, y);
    }
    write(block.text, { size: 10, x: left + indent, width: contentW - indent, after: 1.2 });
  });

  // ---- factor table ----
  sectionHeading('Factor Breakdown', 30);
  write('Each factor is scored out of 25, and a higher score is always better for the business. Zoning is a yes-or-no check.', {
    size: 9, color: COLOR.muted, after: 3
  });

  const colScore = left + contentW * 0.36;
  const colStatus = left + contentW * 0.7;
  const barW = Math.min(30, contentW * 0.19);
  const tableHeader = () => {
    font(7.5, COLOR.faint, 'bold');
    doc.setCharSpace(0.4);
    put('FACTOR', left, y);
    put('SCORE', colScore, y);
    put('STATUS', colStatus, y);
    doc.setCharSpace(0);
    y += 4.5;
    rule();
    y += 3;
  };
  ensure(20);
  tableHeader();

  const keys = [...FACTOR_ORDER.filter((key) => breakdown[key]), ...Object.keys(breakdown).filter((key) => !FACTOR_ORDER.includes(key))];
  keys.forEach((key) => {
    const factor = breakdown[key] || {};
    const color = factorColor(factor);
    const detail = [factor.description, factor.evidence, factorDetailText(factor)]
      .filter((part, i, all) => part && all.indexOf(part) === i)
      .join(' ');
    const detailH = detail ? measure(detail, { size: 8.8, lh: 1.4 }) : 0;
    const rowH = 7 + detailH + 5;
    if (y + rowH > contentBottom) {
      doc.addPage();
      y = margin;
      tableHeader();
    }

    font(10, COLOR.ink, 'bold');
    put(formatFactorLabel(key), left, y);

    const hasScore = !factor.constraint && factor.score !== null && factor.score !== undefined;
    if (hasScore) {
      const share = Math.max(0, Math.min(1, Number(factor.score) / 25));
      doc.setFillColor(COLOR.track);
      doc.roundedRect(colScore, y + 1.2, barW, 2.2, 1.1, 1.1, 'F');
      if (share > 0) {
        doc.setFillColor(color);
        doc.roundedRect(colScore, y + 1.2, Math.max(2.2, barW * share), 2.2, 1.1, 1.1, 'F');
      }
      font(9.5, color, 'bold');
      put(formatFactorScore(factor), colScore + barW + 3, y);
    } else {
      font(9.5, color, 'bold');
      put(formatFactorScore(factor), colScore, y);
    }

    font(9.5, color, 'bold');
    put(fitText(factor.status || '-', right - colStatus), colStatus, y);
    y += 6.5;

    if (detail) write(detail, { size: 8.8, color: COLOR.muted, lh: 1.4 });
    y += 2;
    rule();
    y += 3;
  });

  // ---- pinned space ----
  if (space) {
    sectionHeading('Pinned Space Details');
    const rows = [
      ['Title', space.title || '-'],
      ['Listing', String(space.listing_mode || '').toLowerCase() === 'buy' ? 'For sale' : String(space.listing_mode || '').toLowerCase() === 'rent' ? 'For rent' : (space.listing_mode || '-')],
      ['Price range', formatPrice(space.price_min, space.price_max)],
      ['Address', space.address_text || 'No address provided'],
      ['Contact', space.contact_info || 'No contact info provided'],
      ['Verified', space.verified_at ? String(space.verified_at).slice(0, 10) : '-'],
      ['Listing expires', space.expires_at ? String(space.expires_at).slice(0, 10) : '-']
    ];
    if (space.notes) rows.push(['Notes', space.notes]);
    const valueX = left + 38;
    rows.forEach(([label, value]) => {
      const h = measure(value, { size: 9.5, width: right - valueX });
      ensure(h + 1.5);
      font(9, COLOR.faint);
      put(label, left, y);
      write(value, { size: 9.5, color: COLOR.ink, x: valueX, width: right - valueX, after: 1.5 });
    });
  }

  // ---- disclaimer ----
  y += 4;
  callout('Before you decide', DISCLAIMER, COLOR.muted, COLOR.panel, COLOR.rule);

  // ---- footer on every page ----
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page);
    doc.setDrawColor(COLOR.rule);
    doc.line(left, footerY - 2.5, right, footerY - 2.5);
    font(7.5, COLOR.faint);
    put(`MarketScope Business Feasibility Report  |  ${businessLabel}`, left, footerY);
    put(`Page ${page} of ${pages}`, right, footerY, { align: 'right' });
  }

  return doc;
};
